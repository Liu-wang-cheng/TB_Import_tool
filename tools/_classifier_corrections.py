def apply_corrections(samples: list) -> tuple:
    """应用纠错映射表，返回 (修正后样本列表, 修正数量)"""
    corrected = []
    fix_count = 0
    for title, cat in samples:
        new_cat = _lookup(title, cat)
        if new_cat:
            corrected.append((title, new_cat))
            fix_count += 1
        else:
            corrected.append((title, cat))
    return corrected, fix_count


def _lookup(title: str, cat: str) -> str | None:
    """前缀模糊匹配查找纠错"""
    prefix = title[:20]
    for (key_prefix, key_cat), new_cat in CORRECTIONS.items():
        if cat == key_cat and title.startswith(key_prefix):
            return new_cat
    return None
